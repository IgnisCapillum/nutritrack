    fun search(query: String, category: FoodCategory? = null): List<FoodProduct> {
        val clean = stripAccents(query.trim().lowercase())
        return items.filter { item ->
            if (category != null && category != FoodCategory.ALL) {
                if (!item.category.equals(category.displayName, ignoreCase = true)) {
                    return@filter false
                }
            }
            if (clean.isEmpty()) {
                return@filter true
            }
            val nameMatch = stripAccents(item.name.lowercase()).contains(clean)
            val brandMatch = item.brand?.let { stripAccents(it.lowercase()).contains(clean) } ?: false
            val barcodeMatch = item.barcode.contains(clean)
            nameMatch || brandMatch || barcodeMatch
        }
    }

    fun findByBarcode(barcode: String): FoodProduct? {
        val clean = barcode.trim()
        if (clean.isEmpty()) return null
        return items.firstOrNull { it.barcode == clean }
    }

    private fun stripAccents(s: String): String {
        val normalized = Normalizer.normalize(s, Normalizer.Form.NFD)
        return normalized.replace("\\p{InCombiningDiacriticalMarks}+".toRegex(), "")
    }
